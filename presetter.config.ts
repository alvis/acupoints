import { resolve } from 'node:path';

import next from '@presetter/preset-next';
import react from '@vitejs/plugin-react';
import { asset, preset } from 'presetter';

import { name } from './package.json' with { type: 'json' };

import type { Linter } from 'eslint';
import type { ViteUserConfig } from 'vitest/config';

/** source trees, which live at the repository root rather than under src/ */
const SOURCES = ['app', 'components', 'features', 'utilities', 'content'];

/** data-only modules whose size and literal numbers are the data itself */
const DATA_TABLES = [
  'content/**/*.ts',
  '**/copy.ts',
  '**/*Copy.ts',
  'features/points/labels.ts',
  'utilities/i18n/dictionaries.ts',
];

export default preset(name, {
  // preset-next already composes esm, node, strict, web, and react
  extends: [next],
  variables: {
    source: '.',
    // static export target of next build
    output: 'out',
  },
  scripts: {
    build: 'next build && pagefind --site {output}',
    dev: 'next dev',
    start: 'next start',
  },
  override: {
    scripts: {
      // preset-strict still passes --flag v10_config_lookup_from_file, which
      // ESLint 10 rejects now that file-based config lookup is the default
      'lint:eslint':
        'eslint --fix --format stylish --max-warnings 0 --no-error-on-unmatched-pattern --no-warn-ignored --cache --cache-strategy content',
    },
    assets: {
      // carried over from biome.json; the other format options match the preset
      '.prettierrc.json': { printWidth: 100 },
      // pushes stay fast: tests and coverage run on demand, not as a push gate
      '.husky/pre-push': null,
      // preset-react omits the `--` that forwards staged files to the stage task,
      // which leaves prettier waiting on stdin for every staged component
      '.lintstagedrc.json': asset((current) => ({
        ...current,
        './**/*.[tj]sx': ['presetter run stage --'],
      })),
      'eslint.config.ts': asset<{ default: Linter.Config[] }>((current) => ({
        default: [
          ...(current?.default ?? []),
          {
            name: 'acupoints:data-tables',
            files: DATA_TABLES,
            rules: {
              'max-lines': 'off',
              '@typescript-eslint/no-magic-numbers': 'off',
            },
          },
        ],
      })),
      'tsconfig.json': {
        compilerOptions: {
          // preset-next relaxes strict mode; this project type-checks strictly
          strict: true,
          // next build rewrites jsx to react-jsx; agree with it so neither side churns
          jsx: 'react-jsx',
          // not yet adopted: enabling it surfaces ~40 unguarded index reads
          noUncheckedIndexedAccess: false,
          paths: { '@/*': ['./*'] },
        },
        // route types (PageProps, etc.) generated by next dev / next build
        include: ['.next/types/**/*.ts', '.next/dev/types/**/*.ts'],
        exclude: ['.state', '.worktrees'],
      },
      // unit tests render React components in jsdom against the root-level source trees
      'vitest.config.ts': asset<{ default: ViteUserConfig }>((current, { projectRoot }) => ({
        default: {
          ...current?.default,
          plugins: [react()],
          resolve: { alias: { '@': projectRoot } },
          test: {
            ...current?.default.test,
            environment: 'jsdom',
            include: [`{${SOURCES.join(',')}}/**/*.test.{ts,tsx}`],
            setupFiles: [resolve(projectRoot, 'vitest.setup.ts')],
            // stylesheets stay inert, except raw-text imports that tests read
            css: { include: [/\.css\?raw$/u] },
          },
        },
      })),
    },
  },
});
