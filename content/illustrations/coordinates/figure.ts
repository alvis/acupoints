/**
 * Whole-body placement of every point on the carved standing figure
 * (viewBox 0 0 300 640, the figure drawn from `FIGURE_HALF`). Points of the
 * paired channels sit on the viewer's left half and are mirrored with the
 * figure; Governing and Conception points sit on the midline (x 150).
 *
 * Placement follows the catalogue locations in standard proportional
 * cun: wrist crease y 388, elbow crease y 281, axillary fold
 * y 196, navel y 300, intercostal spaces 13 units apart from the first at
 * y 151, knee y ~500, malleoli y ~604. Arm yin channels run down the inner
 * (front) face of the arm, arm yang channels up the back of the arm; Bladder,
 * Governing and the back-of-body stretches of Small Intestine, San Jiao,
 * Gallbladder and Kidney are on the back figure. Positions are approximate
 * by design: they say where on the body, not a needling site.
 *
 * `from` names an earlier point the course branches from, where the line
 * does not simply continue from the previous point (Stomach 9 descends from
 * Stomach 5; the Bladder's outer back line leaves the nape at Bladder 10).
 */

/** Which carved figure a point is drawn on. */
export type FigureView = 'front' | 'back';

