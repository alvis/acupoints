/** The part of the body a point sits on. */
export type BodyPart = (typeof BODY_PARTS)[number];

/** One point on the whole-body figure. */
export interface FigurePoint {
  /** Point code, e.g. `LI4`. */
  readonly code: string;
  readonly view: FigureView;
  /** Figure units, 0..300 across. */
  readonly x: number;
  /** Figure units, 0..640 down. */
  readonly y: number;
  readonly part: BodyPart;
  /** Earlier point of the same channel the course branches from. */
  readonly from?: string;
}

